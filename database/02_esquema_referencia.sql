-- =====================================================================
--  Pastelería X7 — Paso 2 (OPCIONAL): esquema de referencia
-- =====================================================================
--  Estas son las tablas que Hibernate genera a partir de las entidades
--  Usuario, Producto y Pedido. Sirve para documentar el modelo; no es
--  necesario ejecutarlo, porque la aplicación las crea sola al iniciar.
--  Si prefieres crearlas a mano, ejecútalo en el Query Tool de la base
--  pasteleria_x7 ANTES de iniciar la aplicación.
--
--  Correspondencia Java → PostgreSQL:
--    Long id + @GeneratedValue(IDENTITY) → bigint generated by default as identity
--    String + @Column(length = n)        → varchar(n)
--    columnDefinition = "TEXT"           → text
--    BigDecimal (precision 10, scale 2)  → numeric(10,2)
--    LocalDate / LocalDateTime           → date / timestamp(6)
--    enum + @Enumerated(STRING)          → varchar + check (solo valores válidos)
--    @ManyToOne + @JoinColumn            → columna *_id + foreign key
-- =====================================================================

CREATE TABLE usuario (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    nombre     varchar(100) NOT NULL,
    email      varchar(120) NOT NULL,
    telefono   varchar(9),
    direccion  varchar(150),
    password   varchar(60)  NOT NULL,
    rol        varchar(20)  NOT NULL CHECK (rol IN ('CLIENTE', 'ADMINISTRADOR')),
    CONSTRAINT usuario_pkey     PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE producto (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    nombre       varchar(80)    NOT NULL,
    categoria    varchar(30)    NOT NULL,
    etiqueta     varchar(30),
    precio       numeric(10,2)  NOT NULL,
    descripcion  text           NOT NULL,
    imagen       varchar(500),
    disponible   boolean        NOT NULL,
    CONSTRAINT producto_pkey      PRIMARY KEY (id),
    CONSTRAINT uk_producto_nombre UNIQUE (nombre)
);

CREATE TABLE pedido (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    codigo           varchar(15),
    tipo             varchar(10)   NOT NULL CHECK (tipo IN ('PEDIDO', 'CATERING')),
    usuario_id       bigint        NOT NULL,
    producto_id      bigint,                       -- NULL en catering y pedidos personalizados
    tipo_evento      varchar(50),                  -- solo catering
    detalle          text,
    fecha_entrega    date          NOT NULL,
    monto            numeric(10,2),                -- NULL = "Por confirmar"
    estado           varchar(20)   NOT NULL CHECK (estado IN ('PENDIENTE', 'EN_PREPARACION', 'ENTREGADO')),
    nombre_contacto  varchar(100)  NOT NULL,
    telefono         varchar(9)    NOT NULL,
    direccion        varchar(200)  NOT NULL,
    fecha_registro   timestamp(6)  NOT NULL,
    CONSTRAINT pedido_pkey        PRIMARY KEY (id),
    CONSTRAINT uk_pedido_codigo   UNIQUE (codigo),
    -- Relación usuario 1 ── N pedido
    CONSTRAINT fk_pedido_usuario  FOREIGN KEY (usuario_id)  REFERENCES usuario (id),
    -- Relación producto 1 ── N pedido (opcional)
    CONSTRAINT fk_pedido_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
);
